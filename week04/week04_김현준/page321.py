def lucky_strike(N: int):
    """
    ==========================================================================================
    현재 캐릭터의 점수를 N이라고 할 때 자릿수를 기준으로 점수 N을 반으로 나누어 왼쪽 부분의 각 자릿수의 합과,
    오른쪽 부분의 각 자릿수의 합을 더한 값이 동일한 상황이 "LUCKY"입니다.

    💙예시 
     • 현재 점수가 123,402라면 왼쪽 부분의 각 자릿 수 합은 1+2+3 = 6,
     오른쪽 부분의 각 자릿수의 합은 4+0+2=6입니다.
     두 합이 6으로 동일하므로 "LUCKY"입니다. 럭키스트라이크!

    ⭕입력 조건
     • 첫째 줄에 점수 N 이 장수로 주어집니다. (10<N < 99,999,999) 단, 점수 비의 자릿수는 항상 짝수 형태로만 주어집니다. 
     예를 들어 자릿수가 5인 12,345와 같은 수는 입력으로 들어오지 않습니다.

    ✅출력 조건
     • 첫째 줄에 럭키 스트레이트를 사용할 수 있다면 “LUCKY"를, 사용할 수 없다면 "READY”를 출력합니다.
    ==========================================================================================
    """
    str_N = str(N)
    left=0
    right = 0
    length = len(str_N)
    for i in range(length//2):
        left += ord(str_N[i]) - ord('0')
        right += ord(str_N[length-i-1]) - ord('0')
    if left == right:
        return "LUCKY"
    return "READY"


print(lucky_strike(123_402))

        